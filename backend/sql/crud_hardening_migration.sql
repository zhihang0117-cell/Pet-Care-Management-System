-- Install after the base schema. It hardens the remaining multi-row CRUD
-- operations and records every exceptional points correction.

create table if not exists loyalty_points_adjustment (
  adjustment_id bigint generated by default as identity primary key,
  company_id int not null references companies(company_id) on delete cascade,
  loyalty_id int not null references loyaltymember(loyalty_id) on delete cascade,
  changed_by_account_id int references accounts(account_id) on delete set null,
  old_balance int not null,
  new_balance int not null,
  reason text not null,
  created_at timestamptz not null default now(),
  constraint loyalty_points_adjustment_reason_not_blank check (length(btrim(reason)) > 0),
  constraint loyalty_points_adjustment_balances_nonnegative check (old_balance >= 0 and new_balance >= 0)
);

create index if not exists loyalty_points_adjustment_company_loyalty_idx
  on loyalty_points_adjustment(company_id, loyalty_id, created_at desc);

alter table loyalty_points_adjustment enable row level security;
drop policy if exists tenant_select on loyalty_points_adjustment;
create policy tenant_select on loyalty_points_adjustment for select
  using (company_id = current_company_id());

create or replace function adjust_loyalty_points(
  p_company_id int,
  p_loyalty_id int,
  p_new_balance int,
  p_reason text,
  p_account_id int
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_member loyaltymember%rowtype;
  v_tier text;
begin
  if p_new_balance < 0 or nullif(btrim(p_reason), '') is null then
    raise exception 'A non-negative balance and reason are required' using errcode = 'P0001';
  end if;
  select * into v_member from loyaltymember
    where company_id = p_company_id and loyalty_id = p_loyalty_id for update;
  if not found then raise exception 'Loyalty member not found' using errcode = 'P0002'; end if;

  v_tier := case when p_new_balance >= 1200 then 'Platinum'
    when p_new_balance >= 700 then 'Gold'
    when p_new_balance >= 300 then 'Silver'
    else 'Bronze' end;
  update loyaltymember set points_balance = p_new_balance, tier = v_tier
    where company_id = p_company_id and loyalty_id = p_loyalty_id;
  insert into loyalty_points_adjustment(
    company_id, loyalty_id, changed_by_account_id, old_balance, new_balance, reason
  ) values (
    p_company_id, p_loyalty_id, p_account_id, v_member.points_balance, p_new_balance, btrim(p_reason)
  );
  return jsonb_build_object(
    'loyalty_id', p_loyalty_id, 'points_balance', p_new_balance,
    'tier', v_tier, 'adjustment_reason', btrim(p_reason)
  );
end;
$$;

create or replace function update_account_guarded(
  p_company_id int,
  p_account_id int,
  p_role text,
  p_status text
)
returns accounts
language plpgsql
security definer
set search_path = public
as $$
declare
  v_target accounts%rowtype;
  v_result accounts%rowtype;
begin
  perform account_id from accounts where company_id = p_company_id order by account_id for update;
  select * into v_target from accounts
    where company_id = p_company_id and account_id = p_account_id;
  if not found then raise exception 'Account not found' using errcode = 'P0002'; end if;
  if v_target.role = 'manager' and v_target.account_status = 'active'
    and (coalesce(p_role, v_target.role) <> 'manager' or coalesce(p_status, v_target.account_status) <> 'active')
    and (select count(*) from accounts where company_id = p_company_id and role = 'manager' and account_status = 'active') <= 1
  then
    raise exception 'The company must keep at least one active manager account' using errcode = 'P0001';
  end if;
  update accounts set role = coalesce(p_role, role), account_status = coalesce(p_status, account_status)
    where company_id = p_company_id and account_id = p_account_id returning * into v_result;
  return v_result;
end;
$$;

create or replace function delete_account_guarded(p_company_id int, p_account_id int)
returns accounts
language plpgsql
security definer
set search_path = public
as $$
declare
  v_target accounts%rowtype;
begin
  perform account_id from accounts where company_id = p_company_id order by account_id for update;
  select * into v_target from accounts
    where company_id = p_company_id and account_id = p_account_id;
  if not found then raise exception 'Account not found' using errcode = 'P0002'; end if;
  if v_target.role = 'manager' and v_target.account_status = 'active'
    and (select count(*) from accounts where company_id = p_company_id and role = 'manager' and account_status = 'active') <= 1
  then
    raise exception 'The company must keep at least one active manager account' using errcode = 'P0001';
  end if;
  delete from accounts where company_id = p_company_id and account_id = p_account_id;
  return v_target;
end;
$$;

