create or replace function cancel_approved_redemption(
  p_company_id int,
  p_redemption_id int,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_payment payment%rowtype;
  v_redemption redemption%rowtype;
  v_member loyaltymember%rowtype;
  v_balance int;
  v_tier text;
begin
  if nullif(btrim(p_reason), '') is null then
    raise exception 'A cancellation reason is required' using errcode = 'P0001';
  end if;
  -- Same global lock order as request/decide/verify: payment, redemption, member.
  select * into v_payment from payment
    where company_id = p_company_id and redemption_id = p_redemption_id for update;
  if not found then raise exception 'Linked payment not found' using errcode = 'P0002'; end if;
  if v_payment.status not in ('Pending', 'Unpaid', 'Cancelled') then
    raise exception 'A redemption on a completed payment must be refunded through the payment refund flow'
      using errcode = 'P0001';
  end if;
  select * into v_redemption from redemption
    where company_id = p_company_id and redemption_id = p_redemption_id for update;
  if not found or v_redemption.status <> 'Approved' then
    raise exception 'Only an approved redemption can be cancelled' using errcode = 'P0001';
  end if;
  select * into v_member from loyaltymember
    where company_id = p_company_id and loyalty_id = v_redemption.loyalty_id for update;
  if not found then raise exception 'Loyalty member not found' using errcode = 'P0002'; end if;

  v_balance := v_member.points_balance + coalesce(v_redemption.loyalty_spend, 0);
  v_tier := case when v_balance >= 1200 then 'Platinum'
    when v_balance >= 700 then 'Gold'
    when v_balance >= 300 then 'Silver'
    else 'Bronze' end;
  update loyaltymember set
    points_balance = v_balance, tier = v_tier,
    redemption_made = greatest(coalesce(redemption_made, 0) - 1, 0)
    where company_id = p_company_id and loyalty_id = v_redemption.loyalty_id;
  update redemption set
    status = 'Cancelled', cancelled_date = current_date,
    cancelled_time = localtime, cancellation_reason = btrim(p_reason)
    where company_id = p_company_id and redemption_id = p_redemption_id;
  update payment set redemption_id = null
    where company_id = p_company_id and payment_id = v_payment.payment_id;
  return jsonb_build_object(
    'redemption_id', p_redemption_id, 'status', 'Cancelled',
    'points_returned', coalesce(v_redemption.loyalty_spend, 0),
    'new_points_balance', v_balance
  );
end;
$$;

revoke all on function cancel_approved_redemption(int, int, text) from public, anon, authenticated;
grant execute on function cancel_approved_redemption(int, int, text) to service_role;
